<?php declare( strict_types=1 );

namespace A8C\SpecialProjects\AICanvasWebMCP\Integrations\WooCommerceSubscriptions;

\defined( 'ABSPATH' ) || exit;

/**
 * Builds the note appended to subscription price strings.
 *
 * @since   1.0.0
 * @version 1.0.0
 */
final class PriceNote {
	// region HOOKS

	/**
	 * Appends the example note to the subscription price string.
	 *
	 * @since   1.0.0
	 * @version 1.0.0
	 *
	 * @param   string $price_string The price string WooCommerce Subscriptions generated.
	 *
	 * @return  string
	 */
	public function append( string $price_string ): string {
		return wp_sprintf(
			/* translators: %s: The subscription price string generated by WooCommerce Subscriptions */
			__( '%s (A8CSP AI Canvas WebMCP example note)', 'a8csp-ai-canvas-webmcp' ),
			$price_string
		);
	}

	// endregion
}
